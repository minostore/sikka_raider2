#!/usr/bin/env python3
"""Bump the release minor version and Android/iOS build number before manual release builds."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
pub = root / "pubspec.yaml"
text = pub.read_text(encoding="utf-8")
match = re.search(r"(?m)^version:\s*(\d+)\.(\d+)(?:\.(\d+))?\+(\d+)\s*$", text)
if not match:
    raise SystemExit("Expected pubspec version like 1.2.0+17")
major, minor, patch, build = match.groups()
major, minor, build = int(major), int(minor), int(build) + 1
# A release increments 1.2 -> 1.3; preserve the two-part style if one was used.
version = f"{major}.{minor + 1}" if patch is None else f"{major}.{minor + 1}.0"
full = f"{version}+{build}"
text = text[:match.start()] + f"version: {full}" + text[match.end():]
pub.write_text(text, encoding="utf-8")
(root / "lib/core/app_version.dart").write_text(
    "/// Generated by tool/bump_version.py from pubspec.yaml.\n"
    "class AppVersion {\n  static const current = " + repr(version) + ";\n}\n",
    encoding="utf-8",
)
print(f"Bumped release version: {full}")
